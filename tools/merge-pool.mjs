// Merge several generated pool files into games/toddy-trail/src/endless-pool.js:  node tools/merge-pool.mjs a.js b.js ...
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const out = process.env.POOL_OUT || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'games', 'toddy-trail', 'src', 'endless-pool.js');
const pool = [], seen = new Set();
for (const f of process.argv.slice(2)) {
  const line = fs.readFileSync(f, 'utf8').split('\n').find((l) => l.startsWith('export const POOL = '));
  for (const lv of JSON.parse(line.replace(/^export const POOL = /, '').replace(/;$/, ''))) { const k = JSON.stringify(lv); if (!seen.has(k)) { seen.add(k); pool.push(lv); } }
}
pool.sort((a, b) => a.tier - b.tier || a.best - b.best);
const head = '// GENERATED by tools/gen-endless.mjs (+ tools/merge-pool.mjs): do not edit by hand. Each level was proven winnable (cleanly) by tools/trail-solver.mjs.\n// tier = difficulty band (0 easiest); best = the fewest steps the solver needed (4 steps = 1 second).\n';
fs.writeFileSync(out, head + 'export const POOL = ' + JSON.stringify(pool) + ';\n');
const per = {}; for (const l of pool) per[l.tier] = (per[l.tier] || 0) + 1;
console.log('merged', pool.length, 'levels', JSON.stringify(per), (fs.statSync(out).size / 1024).toFixed(0) + ' KB');
