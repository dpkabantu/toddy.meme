// Builds games/moon-brew/src/season-trays.js: for each Season night (1-7) and tray (1-20), the layout seed.
// The recipe (pieces, size, beans) comes from seasonRecipe() in levels.js; this tool only picks the seed so that
// difficulty rises every tray and every night and the tray can be cleared. Run: node tools/build-season-trays.mjs
import { writeFileSync } from 'node:fs';
import { generate, newGame, tap, hint, difficulty } from '../games/moon-brew/src/core.js';
import { seasonRecipe, trayLevelConfig } from '../games/moon-brew/src/levels.js';

const solvable = (lv) => { const g = newGame(lv); let at = 0; while (g.status === 'playing') { const b = hint(g); if (!b) break; tap(g, b, at += 900); } return g.status === 'won'; };
const table = [], diffs = [];
for (let n = 1; n <= 7; n++) {
  const row = [], drow = [];
  for (let t = 1; t <= 20; t++) {
    const floor = Math.max(t > 1 ? drow[t - 2] + 1 : 0, n > 1 && t <= 14 ? diffs[n - 2][t - 1] + 1 : 0);
    const cands = [];
    for (let s = 0; s < 80; s++) {
      const seed = (800000 + n * 10000 + t * 100 + s) >>> 0, lv = generate({ ...seasonRecipe(n, t), seed, band: 'season' }), d = difficulty(lv);
      if (d >= floor) cands.push({ seed, d, lv });
    }
    // target: a little harder than the Story's own tray of the same number (the Story is the ceiling for a first-time player's first night)
    const want = Math.min(185, difficulty(generate(trayLevelConfig(n - 1, t))) * 1.02);
    const lim = cands.filter((c) => c.d <= floor + 10);   // climb gradually so later trays always have room above
    cands.splice(0, cands.length, ...(lim.length ? lim : cands));
    cands.sort((a, b) => Math.abs(a.d - want) - Math.abs(b.d - want));
    const best = cands.find((c) => solvable(c.lv));   // the layout closest to the target that keeps the climb going
    if (!best) throw new Error('no tray for night ' + n + ' tray ' + t);
    row.push(best.seed); drow.push(best.d);
  }
  table.push(row); diffs.push(drow);
  console.log('night ' + n + ': ' + drow.map((d) => Math.round(d)).join(' '));
}
writeFileSync(new URL('../games/moon-brew/src/season-trays.js', import.meta.url),
  '// GENERATED by tools/build-season-trays.mjs. Do not edit by hand.\n// SEASON_TRAYS[night-1][tray-1] = layout seed. The recipe is seasonRecipe() in levels.js.\nexport const SEASON_TRAYS = ' + JSON.stringify(table) + ';\n');
