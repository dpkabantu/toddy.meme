// Builds games/moon-brew/src/season-trays.js: the 7 Season nights x 20 trays of Moon Brew's Season launch mission.
// Each tray is picked so difficulty rises every tray and every night (night n tray t is harder than tray t-1, and harder than night n-1 tray t).
// Run: node tools/build-season-trays.mjs   (the result is checked in; the server and the game read the same file)
import { writeFileSync } from 'node:fs';
import { generate, newGame, tap, hint, difficulty } from '../games/moon-brew/src/core.js';
import { endlessConfig } from '../games/moon-brew/src/levels.js';

const NIGHTS = 7, TRAYS = 20;
const lo = (n) => 35 + 8 * (n - 1), hi = (n) => 130 + 11 * (n - 1);
const target = (n, t) => lo(n) + (hi(n) - lo(n)) * (t - 1) / (TRAYS - 1);
const cfg = (k, seed) => ({ ...endlessConfig(seed, k), seed, band: 'season' });
const solvable = (lv) => { const g = newGame(lv); let at = 0; while (g.status === 'playing') { const b = hint(g); if (!b) break; tap(g, b, at += 900); } return g.status === 'won'; };

const table = [], diffs = [];
for (let n = 1; n <= NIGHTS; n++) {
  const row = [], drow = [];
  for (let t = 1; t <= TRAYS; t++) {
    const want = target(n, t), floor = Math.max(t > 1 ? drow[t - 2] + 1 : 0, n > 1 ? diffs[n - 2][t - 1] + 1 : 0);
    let best = null;
    for (let k = 0; k <= 24 && !(best && Math.abs(best.d - want) < 2); k++) {
      for (let s = 0; s < 12; s++) {
        const seed = (700000 + n * 10000 + t * 300 + k * 13 + s) >>> 0, lv = generate(cfg(k, seed)), d = difficulty(lv);
        if (d < floor) continue;
        if (!best || Math.abs(d - want) < Math.abs(best.d - want)) { if (solvable(lv)) best = { k, seed, d }; }
      }
    }
    if (!best) throw new Error('no tray for night ' + n + ' tray ' + t);
    row.push([best.k, best.seed]); drow.push(best.d);
  }
  table.push(row); diffs.push(drow);
  console.log('night ' + n + ': ' + drow.map((d) => Math.round(d)).join(' '));
}
writeFileSync(new URL('../games/moon-brew/src/season-trays.js', import.meta.url),
  '// GENERATED by tools/build-season-trays.mjs. Do not edit by hand.\n// Season launch mission: SEASON_TRAYS[night-1][tray-1] = [k, seed] for endlessConfig. Difficulty rises every tray and every night.\n' +
  'export const SEASON_TRAYS = ' + JSON.stringify(table) + ';\n');
